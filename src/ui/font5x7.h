// font5x7.h - Phase 2c: a small, self-authored 5x7 dot-matrix
// bitmap font, used by UiRenderer::DrawLabel.
//
// Deliberately not a real font/atlas: it's rendered as plain solid
// rects through the exact same pipeline as DrawRect, so Phase 2c
// needs zero texture/atlas/font-loading machinery to get readable
// button labels and status text on screen. A proper font atlas is
// a natural later-phase upgrade behind the same DrawLabel(...) call
// signature - callers won't need to change.
//
// Coverage: space, 0-9, A-Z (lowercase input is upper-cased by
// DrawLabel), and a handful of punctuation: . , ! ? : - ( ) ' /
// Unmapped characters fall back to a blank glyph rather than
// asserting/crashing, since this will get typed-string input
// (labels, status text) that isn't fully validated upstream.

