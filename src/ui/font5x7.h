// Linear scan over ~40 entries, called per-character during
// DrawLabel - fine at this scale; revisit only if profiling ever
// says otherwise.
inline const Glyph5x7* FindGlyph5x7(char ch) {
    for (int i = 0; i < kFont5x7GlyphCount; ++i) {
        if (kFont5x7[i].ch == ch) {
            return &kFont5x7[i];
        }
    }
    return nullptr;
}

